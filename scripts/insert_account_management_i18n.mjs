for (const [locale, block] of Object.entries(BLOCKS)) {
  const file = join(localesDir, `${locale}.ts`)
  const source = readFileSync(file, 'utf8')
  if (source.includes('accountManagement:')) {
    console.log(`${locale}: already contains accountManagement, skipping`)
    continue
  }
  // 锚点：sessionSettings 块的结束 "  },\n"（该块在四个语言包中均存在，
  // 且其后紧跟空行 + 下一顶层键）。为稳妥，匹配块起止。
  const anchor = 'sessionSettings: {'
  const start = source.indexOf(anchor)
  if (start < 0) {
    throw new Error(`${locale}: sessionSettings anchor not found`)
  }
  // 从锚点向后找第一个行首 "  },"（顶层块的关闭）
  const closeIdx = source.indexOf('\n  },', start)
  if (closeIdx < 0) {
    throw new Error(`${locale}: sessionSettings block end not found`)
  }
  const insertAt = closeIdx + '\n  },'.length
  const next = source.slice(0, insertAt) + '\n\n' + block.trimEnd() + '\n' + source.slice(insertAt)
  writeFileSync(file, next, 'utf8')
  console.log(`${locale}: inserted accountManagement block (${block.length} chars)`)
}
